package org.aikarasong.plugin.extractor

import org.schabi.newpipe.extractor.InfoItem
import org.schabi.newpipe.extractor.MediaFormat
import org.schabi.newpipe.extractor.NewPipe
import org.schabi.newpipe.extractor.Page
import org.schabi.newpipe.extractor.ServiceList
import org.schabi.newpipe.extractor.linkhandler.SearchQueryHandler
import org.schabi.newpipe.extractor.localization.ContentCountry
import org.schabi.newpipe.extractor.localization.Localization
import org.schabi.newpipe.extractor.playlist.PlaylistInfo
import org.schabi.newpipe.extractor.search.SearchExtractor
import org.schabi.newpipe.extractor.search.SearchInfo
import org.schabi.newpipe.extractor.services.youtube.extractors.YoutubeSearchExtractor
import org.schabi.newpipe.extractor.services.youtube.linkHandler.YoutubeSearchQueryHandlerFactory
import org.schabi.newpipe.extractor.services.youtube.linkHandler.YoutubeStreamLinkHandlerFactory
import org.schabi.newpipe.extractor.stream.StreamInfoItem
import org.schabi.newpipe.extractor.stream.StreamInfo as ExtractorStreamInfo

/** [Backend] backed by NewPipeExtractor (no API key needed). All calls block on network I/O. */
class NewPipeBackend : Backend {
    init {
        synchronized(NewPipeBackend::class.java) {
            if (NewPipe.getDownloader() == null) {
                NewPipe.init(OkHttpDownloader(), Localization("zh", "TW"), ContentCountry("TW"))
            }
        }
    }

    private val service = ServiceList.YouTube
    private val cursors = CursorStore<SearchCursor>()

    /** Where the next page of one search starts: the query itself and the page marker. */
    private class SearchCursor(val handler: SearchQueryHandler, val page: Page)

    override fun searchPage(
        query: String,
        cursor: String?,
    ): PageDto {
        if (cursor != null) {
            // A token the plug-in no longer knows (its process was restarted) simply ends the list.
            val saved = cursors.get(cursor) ?: return PageDto(emptyList())
            val more = SearchInfo.getMoreItems(service, saved.handler, saved.page)
            return pageOf(more.items, more.nextPage, saved.handler)
        }
        return try {
            val handler =
                service.searchQHFactory.fromQuery(query, listOf(YoutubeSearchQueryHandlerFactory.VIDEOS), "")
            val extractor = service.getSearchExtractor(handler) as YoutubeSearchExtractor
            extractor.fetchPage()
            val first = extractor.initialPage
            pageOf(first.items, first.nextPage, handler)
        } catch (_: SearchExtractor.NothingFoundException) {
            // YouTube answers some exact titles with no results; that is "nothing", not a failure.
            PageDto(emptyList())
        }
    }

    private fun pageOf(
        items: List<InfoItem>,
        next: Page?,
        handler: SearchQueryHandler,
    ) = PageDto(
        items.filterIsInstance<StreamInfoItem>().filterNot { it.isShortFormContent }.mapNotNull(::toVideo),
        next?.let { cursors.put(SearchCursor(handler, it)) },
    )

    override fun resolveStream(videoId: String): StreamDto =
        pickStream(ExtractorStreamInfo.getInfo(service, "$WATCH_URL$videoId"))

    override fun playlist(playlistId: String): List<VideoDto> {
        val url = "$PLAYLIST_URL$playlistId"
        val info = PlaylistInfo.getInfo(service, url)
        val items = info.relatedItems.toMutableList()
        var page = info.nextPage
        while (page != null && items.size < MAX_PLAYLIST_ITEMS) {
            val more = PlaylistInfo.getMoreItems(service, url, page)
            items += more.items
            page = more.nextPage
        }
        return items.mapNotNull(::toVideo)
    }

    override fun details(videoId: String): DetailsDto {
        val info = ExtractorStreamInfo.getInfo(service, "$WATCH_URL$videoId")
        val tracks =
            info.subtitles
                .filter { !it.isAutoGenerated }
                .groupBy { it.languageTag }
                .map { (lang, streams) ->
                    TrackDto(lang, streams.map { FormatDto(it.format?.suffix.orEmpty(), it.content) })
                }
        return DetailsDto(
            tracks = tracks,
            description = info.description?.content.orEmpty(),
            autoLangs = info.subtitles.filter { it.isAutoGenerated }.map { it.languageTag },
            allLangs = info.subtitles.map { it.languageTag },
        )
    }

    private fun toVideo(item: StreamInfoItem): VideoDto? {
        val id = runCatching { YoutubeStreamLinkHandlerFactory.getInstance().getId(item.url) }.getOrNull()
        return id?.let {
            VideoDto(
                id = it,
                title = item.name,
                channel = item.uploaderName.orEmpty(),
                durationSec = item.duration.coerceAtLeast(0).toInt(),
                thumb = item.thumbnails.firstOrNull()?.url,
                views = item.viewCount,
            )
        }
    }

    /**
     * Prefers separate H.264 video (up to [MAX_HEIGHT]p) plus AAC audio, because the pre-muxed streams top out at
     * 360p. Falls back to a muxed stream.
     */
    private fun pickStream(info: ExtractorStreamInfo): StreamDto {
        val video =
            info.videoOnlyStreams
                .filter { it.format == MediaFormat.MPEG_4 && it.isUrl && it.height in 1..MAX_HEIGHT }
                .maxByOrNull { it.height }
        val audio =
            info.audioStreams
                .filter { it.format == MediaFormat.M4A && it.isUrl }
                .maxByOrNull { it.averageBitrate }
        if (video != null && audio != null) return StreamDto(video.content, audio.content)

        val muxed =
            info.videoStreams
                .filter { it.format == MediaFormat.MPEG_4 && it.isUrl }
                .maxByOrNull { it.height }
        return muxed?.let { StreamDto(it.content) } ?: error("No playable H.264 stream for ${info.id}")
    }

    private companion object {
        const val WATCH_URL = "https://www.youtube.com/watch?v="
        const val MAX_HEIGHT = 720
        const val PLAYLIST_URL = "https://www.youtube.com/playlist?list="
        const val MAX_PLAYLIST_ITEMS = 300
    }
}
